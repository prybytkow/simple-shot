const systemLocaleToLang: Record<string, LangCode> = {
  en: 'en', 'en-US': 'en', 'en-GB': 'en',
  ru: 'ru', 'ru-RU': 'ru',
  zh: 'zh', 'zh-CN': 'zh', 'zh-TW': 'zh',
  pl: 'pl', 'pl-PL': 'pl',
  ua: 'ua', uk: 'ua', 'uk-UA': 'ua', 'ua-UA': 'ua',
  by: 'by', be: 'by', 'be-BY': 'by', 'by-BY': 'by',
  it: 'it', 'it-IT': 'it',
  es: 'es', 'es-ES': 'es', 'es-MX': 'es',
  pt: 'pt', 'pt-BR': 'pt', 'pt-PT': 'pt',
  fr: 'fr', 'fr-FR': 'fr', 'fr-CA': 'fr',
};

/** Resolve settings language ('system' or '') + app locale to supported lang code. Default: en. */
export function resolveLanguage(settingsLang: string | undefined, appLocale: string): LangCode {
  // Legacy settings: ISO 639-1 "uk"/"be" → app codes "ua"/"by"
  const normalized =
    settingsLang === 'uk' ? 'ua' :
    settingsLang === 'be' ? 'by' :
    settingsLang;
  if (normalized && normalized !== 'system' && translations[normalized]) {
    return normalized as LangCode;
  }
  const locale = (appLocale || 'en').split('-')[0];
  const full = appLocale || 'en';
  return systemLocaleToLang[full] || systemLocaleToLang[locale] || 'en';
}

/** Get all translation strings for a language. */
export function getTranslations(lang: LangCode): Record<string, string> {
  return translations[lang] || translations.en;
}

